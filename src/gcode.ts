import type { NormalizedGeometry, Point } from './svg.js';

export interface GcodeOptions {
  feedRate: number;
  travelFeedRate: number;
  safeZ: number;
  laserMode: boolean;
  laserPower: number;
}

function formatNumber(value: number): string {
  const rounded = Math.abs(value) < 0.000001 ? 0 : value;
  return rounded.toFixed(4).replace(/\.?0+$/, '');
}

function formatPoint(point: Point): string {
  return `X${formatNumber(point.x)} Y${formatNumber(point.y)}`;
}

function scalePoint(point: Point, scale: number): Point {
  return {
    x: point.x * scale,
    y: point.y * scale
  };
}

export function generateGcode(geometry: NormalizedGeometry, targetWidthMm: number, options: GcodeOptions): string {
  if (geometry.width <= 0) {
    throw new Error('SVG geometry width harus lebih dari 0.');
  }

  const scale = targetWidthMm / geometry.width;
  const lines: string[] = [
    '; Generated by autogcode',
    `; Target width: ${targetWidthMm}mm`,
    'G21',
    'G90',
    `G0 Z${formatNumber(options.safeZ)}`
  ];

  if (options.laserMode) {
    lines.push('M4 S0');
  }

  for (const polyline of geometry.polylines) {
    if (polyline.length < 2) continue;
    const [first, ...rest] = polyline.map((point) => scalePoint(point, scale));
    if (!first) continue;

    lines.push(`G0 ${formatPoint(first)} F${formatNumber(options.travelFeedRate)}`);
    if (!options.laserMode) {
      lines.push('G1 Z0');
    } else {
      lines.push(`M4 S${formatNumber(options.laserPower)}`);
    }

    for (const point of rest) {
      lines.push(`G1 ${formatPoint(point)} F${formatNumber(options.feedRate)}`);
    }

    if (!options.laserMode) {
      lines.push(`G0 Z${formatNumber(options.safeZ)}`);
    } else {
      lines.push('M5');
    }
  }

  if (options.laserMode) {
    lines.push('M5');
  }
  lines.push(`G0 Z${formatNumber(options.safeZ)}`);
  lines.push('G0 X0 Y0');
  lines.push('M2');

  return `${lines.join('\n')}\n`;
}
